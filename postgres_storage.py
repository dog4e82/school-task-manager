"""PostgreSQL persistence for the web service; SQLite remains the local default."""

import re
import json
import sqlite3

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict, make_conninfo
from psycopg.pq import TransactionStatus

from notice_ai import Cache


SCHEMA = "moa"


class Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


def row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


def translate(statement):
    """Translate only the fixed SQL used by Store and Cache; values stay bound."""
    statement = statement.strip()
    if statement.startswith("PRAGMA"):
        return None
    if statement == "BEGIN IMMEDIATE":
        # Cross-process transaction lock preserves budget checks and record merges.
        return "SELECT pg_advisory_xact_lock(730299615)"
    statement = re.sub(r"\bBLOB\b", "BYTEA", statement)
    statement = statement.replace("id INTEGER PRIMARY KEY, data TEXT", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, data TEXT")
    if statement.startswith("INSERT OR IGNORE INTO"):
        statement = statement.replace("INSERT OR IGNORE INTO", "INSERT INTO", 1) + " ON CONFLICT DO NOTHING"
    return statement.replace("?", "%s")


class Connection:
    def __init__(self, dsn, readonly=False, initialize=False):
        self.raw = None
        try:
            config = conninfo_to_dict(dsn)
            # Schema creation uses a direct endpoint. Request traffic stays pooled.
            host = config.get("host", "")
            labels = host.split(".")
            if initialize and host.endswith(".neon.tech") and labels[0].endswith("-pooler"):
                config["host"] = ".".join([labels[0][:-7], *labels[1:]])
                dsn = make_conninfo(**config)
            mode = config.get("sslmode", "require")
            if mode not in ("require", "verify-ca", "verify-full"):
                raise ValueError("TLS is required")
            self.raw = psycopg.connect(dsn, sslmode=mode, connect_timeout=10,
                                       prepare_threshold=None, row_factory=row_factory)
            self.raw.read_only = readonly
            if initialize:
                self.raw.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(SCHEMA)))
            self.raw.commit()
        except (psycopg.Error, ValueError, TypeError):
            if self.raw is not None:
                self.raw.close()
            raise ValueError("DATABASE_URL의 PostgreSQL 연결·TLS·접근 권한을 확인하세요. 연결 문자열은 출력하지 않습니다.") from None
        self.total_changes = 0
        self.schema = SCHEMA

    def prepare_transaction(self):
        if self.raw.info.transaction_status == TransactionStatus.IDLE:
            # PgBouncer transaction pooling does not preserve session SET values.
            self.raw.execute(sql.SQL("SET LOCAL search_path TO {}").format(sql.Identifier(self.schema)))

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        self.raw.rollback() if kind else self.raw.commit()
        return False

    def execute(self, statement, parameters=()):
        query = translate(statement)
        if query is None:
            return None
        try:
            self.prepare_transaction()
            cursor = self.raw.execute(query, parameters or None)
        except psycopg.IntegrityError:
            raise sqlite3.IntegrityError("Database constraint rejected the operation") from None
        if statement.lstrip().startswith(("INSERT", "UPDATE", "DELETE")):
            self.total_changes += max(0,cursor.rowcount)
        return cursor

    def executemany(self, statement, rows):
        self.prepare_transaction()
        cursor = self.raw.cursor()
        cursor.executemany(translate(statement),rows)
        self.total_changes += max(0,cursor.rowcount)
        return cursor

    def executescript(self, script):
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self.raw.commit()

    def close(self):
        self.raw.close()


class PostgresCache(Cache):
    def __init__(self, dsn, readonly=False):
        self._loaded = None
        self.conn = Connection(dsn,readonly=readonly,initialize=not readonly)
        if not readonly:
            try:
                with self.conn:
                    self.conn.execute("CREATE TABLE IF NOT EXISTS analyses (key TEXT PRIMARY KEY, post_key TEXT, model TEXT, status TEXT, result TEXT, metrics TEXT, updated_at TEXT)")
                    self.conn.execute("CREATE TABLE IF NOT EXISTS runs (id INTEGER PRIMARY KEY, data TEXT)")
            except Exception:
                self.conn.close()
                raise

    def preload(self, keys):
        rows = self.conn.execute("SELECT key,status,result,metrics FROM analyses WHERE key=ANY(?)", (list(keys),)).fetchall()
        self._loaded = {row["key"]:{"status":row["status"],"result":json.loads(row["result"]) if row["result"] else None,
                                    "metrics":json.loads(row["metrics"]) if row["metrics"] else None} for row in rows}

    def get(self, key):
        return self._loaded.get(key) if self._loaded is not None else super().get(key)
